// dock frame → world
export function d2w(x, z) {
  const c = Math.cos(DOCK_YAW), s = Math.sin(DOCK_YAW);
  return [x * c + z * s, -x * s + z * c];
}
export const OD = [d2w(216, 60), d2w(-269, 60), d2w(-216, -60), d2w(270, -60)]; // SW, NW, NE, SE water corners

